-- Run as the schema user that LogLens will use (Oracle 19c+ compatible).
CREATE TABLE error_knowledge (
    error_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    technology     VARCHAR2(60) NOT NULL,
    error_code     VARCHAR2(120) NOT NULL,
    title          VARCHAR2(250) NOT NULL,
    description    CLOB NOT NULL,
    likely_causes  CLOB NOT NULL,
    remediation    CLOB NOT NULL,
    verification   CLOB NOT NULL,
    match_terms    CLOB NOT NULL,
    source_url     VARCHAR2(1000),
    is_active      CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT error_knowledge_active_ck CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT error_knowledge_uk UNIQUE (technology, error_code)
);

CREATE INDEX error_knowledge_active_ix ON error_knowledge (is_active, technology, error_code);
